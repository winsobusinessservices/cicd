import fs from 'fs';
import path from 'path';
import { db } from '../db/index.js';

export interface ProjectRow {
  id: number;
  name: string;
  slug: string;
  description: string;
  project_path: string;
  env_vars: string;
  created_by: string;
  created_at: string;
  updated_at: string;
}

export interface PipelineStepRow {
  id: number;
  project_id: number;
  step_order: number;
  name: string;
  command: string;
  working_dir: string;
  is_enabled: number;
  continue_on_error: number;
  created_at: string;
  updated_at: string;
}

export interface StepInput {
  id?: number;
  step_order?: number;
  name: string;
  command: string;
  working_dir?: string;
  is_enabled?: boolean;
  continue_on_error?: boolean;
}

export class ProjectService {
  /**
   * Parse a physical .env file from disk into a key-value record
   */
  public static parseEnvFile(filePath: string): Record<string, string> {
    try {
      if (!fs.existsSync(filePath)) return {};
      const content = fs.readFileSync(filePath, 'utf-8');
      const lines = content.split('\n');
      const vars: Record<string, string> = {};
      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const idx = trimmed.indexOf('=');
        if (idx !== -1) {
          const key = trimmed.slice(0, idx).trim();
          let val = trimmed.slice(idx + 1).trim();
          // Strip surrounding quotes
          if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
            val = val.slice(1, -1);
          }
          if (key) {
            vars[key] = val;
          }
        }
      }
      return vars;
    } catch {
      return {};
    }
  }

  /**
   * Physically write and synchronize the .env file in the host project folder
   */
  public static syncEnvFileToDisk(projectPath: string, envVars: Record<string, string>, projectName?: string): boolean {
    try {
      if (!projectPath) return false;
      const normalizedPath = path.resolve(projectPath);
      if (!fs.existsSync(normalizedPath)) {
        fs.mkdirSync(normalizedPath, { recursive: true });
      }

      const envFilePath = path.join(normalizedPath, '.env');
      const lines: string[] = [
        `# Auto-generated by Varex Self-Deploying CI/CD Platform`,
        `# Project: ${projectName || 'Varex Project'}`,
        `# Updated At: ${new Date().toISOString()}`,
        '',
      ];

      for (const [key, value] of Object.entries(envVars || {})) {
        const cleanKey = key.trim();
        if (!cleanKey) continue;
        const stringVal = String(value ?? '');
        // Quote values that have spaces, newlines, or quotes
        const needsQuotes = stringVal.includes(' ') || stringVal.includes('\n') || stringVal.includes('"');
        const formattedVal = needsQuotes ? `"${stringVal.replace(/"/g, '\\"')}"` : stringVal;
        lines.push(`${cleanKey}=${formattedVal}`);
      }

      fs.writeFileSync(envFilePath, lines.join('\n') + '\n', 'utf-8');
      return true;
    } catch (err: any) {
      console.error(`[ProjectService] Failed to write .env file to ${projectPath}:`, err.message);
      return false;
    }
  }

  public static getAllProjects() {
    const projects = db.prepare(`
      SELECT p.*,
        (SELECT COUNT(*) FROM pipeline_steps WHERE project_id = p.id) as step_count,
        (SELECT status FROM deployments WHERE project_id = p.id ORDER BY id DESC LIMIT 1) as last_deploy_status,
        (SELECT started_at FROM deployments WHERE project_id = p.id ORDER BY id DESC LIMIT 1) as last_deploy_at
      FROM projects p
      ORDER BY p.updated_at DESC
    `).all() as unknown as any[];

    return projects.map((p) => {
      let envVars: Record<string, string> = {};
      try {
        envVars = JSON.parse(p.env_vars || '{}');
      } catch {
        envVars = {};
      }

      // If empty in DB, check if .env file exists on disk
      if (Object.keys(envVars).length === 0 && p.project_path) {
        const envPath = path.join(p.project_path, '.env');
        if (fs.existsSync(envPath)) {
          envVars = this.parseEnvFile(envPath);
        }
      }

      return {
        ...p,
        env_vars: envVars,
        step_count: Number(p.step_count || 0),
      };
    });
  }

  public static getProjectById(id: number) {
    const project = db.prepare('SELECT * FROM projects WHERE id = ?').get(id) as unknown as ProjectRow | undefined;
    if (!project) return null;

    let envVars: Record<string, string> = {};
    try {
      envVars = JSON.parse(project.env_vars || '{}');
    } catch {
      envVars = {};
    }

    // If empty in DB, automatically read existing .env file from host directory
    if (Object.keys(envVars).length === 0 && project.project_path) {
      const diskEnvPath = path.join(project.project_path, '.env');
      if (fs.existsSync(diskEnvPath)) {
        envVars = this.parseEnvFile(diskEnvPath);
        if (Object.keys(envVars).length > 0) {
          db.prepare('UPDATE projects SET env_vars = ? WHERE id = ?').run(JSON.stringify(envVars), id);
        }
      }
    }

    const steps = db.prepare(`
      SELECT * FROM pipeline_steps WHERE project_id = ? ORDER BY step_order ASC
    `).all(id) as unknown as PipelineStepRow[];

    return {
      ...project,
      env_vars: envVars,
      steps: steps.map((s) => ({
        ...s,
        is_enabled: s.is_enabled === 1,
        continue_on_error: s.continue_on_error === 1,
      })),
    };
  }

  public static createProject(data: {
    name: string;
    description?: string;
    project_path: string;
    env_vars?: Record<string, string>;
    created_by: string;
    steps?: StepInput[];
  }) {
    const now = new Date().toISOString();
    const slug = data.name.toLowerCase().replace(/[^a-z0-9-_]/g, '-').replace(/-+/g, '-');

    let envVarsToUse = data.env_vars || {};
    // If no env vars supplied, read existing .env on disk if present
    if (Object.keys(envVarsToUse).length === 0 && data.project_path) {
      const existingEnvPath = path.join(data.project_path, '.env');
      if (fs.existsSync(existingEnvPath)) {
        envVarsToUse = this.parseEnvFile(existingEnvPath);
      }
    }

    const envVarsStr = JSON.stringify(envVarsToUse);

    const result = db.prepare(`
      INSERT INTO projects (name, slug, description, project_path, env_vars, created_by, created_at, updated_at)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    `).run(
      data.name,
      slug,
      data.description || '',
      data.project_path,
      envVarsStr,
      data.created_by,
      now,
      now
    );

    const projectId = Number(result.lastInsertRowid);

    // If initial steps provided, save them
    if (data.steps && data.steps.length > 0) {
      this.savePipelineSteps(projectId, data.steps);
    }

    // Sync physical .env file to host directory
    if (Object.keys(envVarsToUse).length > 0 && data.project_path) {
      this.syncEnvFileToDisk(data.project_path, envVarsToUse, data.name);
    }

    return this.getProjectById(projectId);
  }

  public static updateProject(id: number, data: {
    name?: string;
    description?: string;
    project_path?: string;
    env_vars?: Record<string, string>;
  }) {
    const project = db.prepare('SELECT * FROM projects WHERE id = ?').get(id) as unknown as ProjectRow | undefined;
    if (!project) return null;

    const now = new Date().toISOString();
    const name = data.name ?? project.name;
    const description = data.description ?? project.description;
    const project_path = data.project_path ?? project.project_path;
    const env_vars = data.env_vars ? JSON.stringify(data.env_vars) : project.env_vars;

    db.prepare(`
      UPDATE projects
      SET name = ?, description = ?, project_path = ?, env_vars = ?, updated_at = ?
      WHERE id = ?
    `).run(name, description, project_path, env_vars, now, id);

    // Sync to disk if env_vars was provided
    if (data.env_vars && project_path) {
      this.syncEnvFileToDisk(project_path, data.env_vars, name);
    }

    return this.getProjectById(id);
  }

  public static deleteProject(id: number): boolean {
    const result = db.prepare('DELETE FROM projects WHERE id = ?').run(id);
    return result.changes > 0;
  }

  public static savePipelineSteps(projectId: number, steps: StepInput[]) {
    const now = new Date().toISOString();

    // Use transaction for atomic replacement of steps
    db.exec('BEGIN TRANSACTION;');
    try {
      db.prepare('DELETE FROM pipeline_steps WHERE project_id = ?').run(projectId);

      const insertStmt = db.prepare(`
        INSERT INTO pipeline_steps (project_id, step_order, name, command, working_dir, is_enabled, continue_on_error, created_at, updated_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
      `);

      steps.forEach((step, index) => {
        const order = index + 1;
        const isEnabled = step.is_enabled === false ? 0 : 1;
        const continueOnError = step.continue_on_error === true ? 1 : 0;
        insertStmt.run(
          projectId,
          order,
          step.name.trim(),
          step.command.trim(),
          (step.working_dir || '').trim(),
          isEnabled,
          continueOnError,
          now,
          now
        );
      });

      db.prepare('UPDATE projects SET updated_at = ? WHERE id = ?').run(now, projectId);
      db.exec('COMMIT;');
    } catch (err) {
      db.exec('ROLLBACK;');
      throw err;
    }

    return this.getStepsByProjectId(projectId);
  }

  public static getStepsByProjectId(projectId: number) {
    const steps = db.prepare(`
      SELECT * FROM pipeline_steps WHERE project_id = ? ORDER BY step_order ASC
    `).all(projectId) as unknown as PipelineStepRow[];

    return steps.map((s) => ({
      ...s,
      is_enabled: s.is_enabled === 1,
      continue_on_error: s.continue_on_error === 1,
    }));
  }

  /**
   * Update project environment variables and physically write .env to project folder
   */
  public static updateProjectEnvVars(id: number, envVars: Record<string, string>) {
    const now = new Date().toISOString();
    const envVarsStr = JSON.stringify(envVars || {});
    db.prepare(`
      UPDATE projects
      SET env_vars = ?, updated_at = ?
      WHERE id = ?
    `).run(envVarsStr, now, id);

    const project = db.prepare('SELECT * FROM projects WHERE id = ?').get(id) as unknown as ProjectRow | undefined;
    if (project && project.project_path) {
      this.syncEnvFileToDisk(project.project_path, envVars, project.name);
    }

    return this.getProjectById(id);
  }
}
